        'relative z-50 max-h-80 min-w-[8rem] overflow-hidden rounded-xl border border-white/[0.1] bg-[#16181D] text-zinc-100 shadow-[0_16px_48px_rgba(0,0,0,0.65)] animate-in fade-in-0 zoom-in-95',
